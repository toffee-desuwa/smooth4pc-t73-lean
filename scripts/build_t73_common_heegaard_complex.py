def frac(value: Fraction) -> str:
    return f"{value.numerator}/{value.denominator}"


def triangulation_document(model: dict[str, Any]) -> dict[str, Any]:
    by_dimension = model["T_simplices_by_dimension"]
    document = {
        "schema": "t73_common_torus_triangulation/v1",
        "generator": "scripts/build_t73_common_heegaard_complex.py",
        "period": PERIOD,
        "vertex_index_rule": "index = 16*x + 4*y + z for (x,y,z) in (Z/4)^3",
        "encoding": (
            "T-simplices are sorted tuples of T-vertex indices.  T'-vertices are "
            "indexed by the global order (dimension, sorted tuple) over the simplices "
            "of T, so T'-vertex i < 64 is the T-vertex i.  T'-tetrahedra are the "
            "maximal chains v<e<f<t written as increasing 4-tuples of T'-vertex indices."
        ),
        "T": {
            "vertices": [list(vcoords(v)) for v, in by_dimension[0]],
            "edges": [list(edge) for edge in by_dimension[1]],
            "triangles": [list(triangle) for triangle in by_dimension[2]],
            "tetrahedra": [list(tet) for tet in by_dimension[3]],
            "integer_lifts": {
                "note": "one lift per simplex, ordered like the sorted index tuple",
                "edges": [
                    [list(point) for point in model["lift_of"][edge]] for edge in by_dimension[1]
                ],
                "triangles": [
                    [list(point) for point in model["lift_of"][triangle]]
                    for triangle in by_dimension[2]
                ],
                "tetrahedra": [
                    [list(point) for point in model["lift_of"][tet]] for tet in by_dimension[3]
                ],
            },
        },
        "Tprime": {
            "vertex_simplex_of_T": [list(simplex) for simplex in model["Tprime_vertex_simplex"]],
            "vertex_barycentre_mod_period": [
                [frac(coord) for coord in point] for point in model["Tprime_vertex_barycentre"]
            ],
            "tetrahedra": [list(tet) for tet in model["Tprime_tetrahedra"]],
            "simplex_count": len(model["Tprime_simplices"]),
        },
        "checks": model["checks"],
    }
    document = normalise(document)
    document["document_sha256"] = canonical_sha(document)
    return document


def spine_document(model: dict[str, Any], names: Sequence[str], label: str) -> dict[str, Any]:
    document: dict[str, Any] = {
        "schema": "t73_spine_pair/v1",
        "generator": "scripts/build_t73_common_heegaard_complex.py",
        "model": label,
        "period": PERIOD,
        "triangulation": "geometry/t73_common_torus_triangulation.json",
        "rank_formula": "rank = E - V + components",
        "spines": {},
    }
    for name in names:
        spine = model["spines"][name]
        document["spines"][name] = {
            key: value for key, value in spine.items() if key != "kprime_simplices"
        }
        document["spines"][name]["edge_coordinates"] = [
            [list(vcoords(a)), list(vcoords(b))] for a, b in spine["edges"]
        ]
    document["all_ranks_are_three"] = all(
        model["spines"][name]["rank"] == 3 for name in names
    )
    document["all_subdivided_spines_full_in_Tprime"] = all(
        model["spines"][name]["subdivided_full_subcomplex_of_Tprime"] for name in names
    )
    document["fullness_note"] = (
        "full_subcomplex_of_T records the literal fullness test in T and is False: "
        "e.g. the T-edge joining two spine vertices on different axis circles is not "
        "a spine edge.  The regular-neighbourhood theorem is applied to the "
        "subdivided spine K', which is always full in T' "
        "(subdivided_full_subcomplex_of_Tprime), and the certificate actually used is "
        "the explicit elementary collapse produced by "
        "scripts/verify_elementary_collapse.py."
    )
    document = normalise(document)
    document["document_sha256"] = canonical_sha(document)
    return document


def handlebody_document(model: dict[str, Any]) -> dict[str, Any]:
    handlebodies = {}
    for name, report in model["handlebodies"].items():
        handlebodies[name] = {
            key: value
            for key, value in report.items()
            if key not in {"boundary_triangles"}
        }
        handlebodies[name]["boundary_triangles"] = [
            list(triangle) for triangle in report["boundary_triangles"]
        ]
    document = {
        "schema": "t73_handlebody_pair_dual_block/v1",
        "generator": "scripts/build_t73_common_heegaard_complex.py",
        "period": PERIOD,
        "triangulation": "geometry/t73_common_torus_triangulation.json",
        "definition": (
            "H^0 = N(K^0;T') = subcomplex of T' generated by the T'-tetrahedra whose "
            "minimal chain element is a vertex of K^0 (union of the dual blocks D(sigma), "
            "sigma in K^0).  H^1 = closure of the complement, i.e. the subcomplex "
            "generated by the remaining T'-tetrahedra.  No barycentre distance "
            "comparison is used."
        ),
        "handlebodies": handlebodies,
        "pair_checks": model["pair_checks"],
        "translation": model["translation"],
    }
    document = normalise(document)
    document["document_sha256"] = canonical_sha(document)
    return document


def documents(model: dict[str, Any]) -> dict[Path, dict[str, Any]]:
    return {
        TRIANGULATION_OUTPUT: triangulation_document(model),
        JOHNSON_SPINE_OUTPUT: spine_document(model, ("K_J0", "K_J1"), "johnson"),
        AR_SPINE_OUTPUT: spine_document(model, ("K_AR0", "K_AR1"), "ar"),
        HANDLEBODY_OUTPUT: handlebody_document(model),
    }


def dump(document: dict[str, Any]) -> str:
    return json.dumps(document, sort_keys=True, separators=(",", ":")) + "\n"


