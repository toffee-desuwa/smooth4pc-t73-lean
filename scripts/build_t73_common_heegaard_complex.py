def spine_vertices_and_edges(base_point: Sequence[int]) -> tuple[set[int], set[Simplex]]:
    vertices: set[int] = set()
    edges: set[Simplex] = set()
    for axis in range(3):
        for step in range(PERIOD):
            head = list(base_point)
            head[axis] = base_point[axis] + step
            tail = list(base_point)
            tail[axis] = base_point[axis] + step + 1
            vertices.add(vid(head))
            vertices.add(vid(tail))
            edge = tuple(sorted((vid(head), vid(tail))))
            if len(set(edge)) != 2:
                raise AssertionError("degenerate spine edge")
            edges.add(edge)
    return vertices, edges


def build_spine(model: dict[str, Any], base_point: Sequence[int]) -> dict[str, Any]:
    vertices, edges = spine_vertices_and_edges(base_point)
    if len(vertices) != 10 or len(edges) != 12:
        raise AssertionError(f"spine at {tuple(base_point)} is not 10 vertices / 12 edges")

    t_edges = set(model["T_simplices_by_dimension"][1])
    if not edges <= t_edges:
        raise AssertionError("a spine edge is not an edge of T")

    adjacency: dict[int, set[int]] = defaultdict(set)
    for a, b in edges:
        adjacency[a].add(b)
        adjacency[b].add(a)
    unseen = set(vertices)
    components = 0
    while unseen:
        start = unseen.pop()
        components += 1
        stack = [start]
        while stack:
            current = stack.pop()
            for other in adjacency[current]:
                if other in unseen:
                    unseen.discard(other)
                    stack.append(other)
    rank = len(edges) - len(vertices) + components

    spine_simplices = {(v,) for v in vertices} | set(edges)
    non_full_witnesses: list[list[int]] = []
    for dimension in (1, 2, 3):
        for simplex in model["T_simplices_by_dimension"][dimension]:
            if set(simplex) <= vertices and simplex not in spine_simplices:
                non_full_witnesses.append(list(simplex))

    tp_index = model["Tprime_vertex_index"]
    kprime_vertices = sorted({tp_index[(v,)] for v in vertices} | {tp_index[e] for e in edges})
    kprime_edges = sorted(
        tuple(sorted((tp_index[(v,)], tp_index[edge])))
        for edge in edges
        for v in edge
    )
    if len(kprime_edges) != 24 or len(set(kprime_edges)) != 24:
        raise AssertionError("subdivided spine does not have 24 edges")
    kprime_simplices = {(v,) for v in kprime_vertices} | set(kprime_edges)

    kprime_vertex_set = set(kprime_vertices)
    kprime_full_in_tprime = True
    for simplex in model["Tprime_simplices"]:
        if set(simplex) <= kprime_vertex_set and simplex not in kprime_simplices:
            kprime_full_in_tprime = False
            break

    return {
        "base_point": [int(c) % PERIOD for c in base_point],
        "vertices": sorted(vertices),
        "vertex_coordinates": [list(vcoords(v)) for v in sorted(vertices)],
        "edges": sorted(edges),
        "components": components,
        "rank": rank,
        "full_subcomplex_of_T": not non_full_witnesses,
        "non_full_witnesses_in_T": sorted(non_full_witnesses),
        "subdivided_vertices": kprime_vertices,
        "subdivided_edges": kprime_edges,
        "subdivided_full_subcomplex_of_Tprime": kprime_full_in_tprime,
        "kprime_simplices": kprime_simplices,
    }


