# the base triangulation T and its barycentric subdivision T'
# --------------------------------------------------------------------------


def build_base_triangulation() -> dict[str, Any]:
    lift_of: dict[Simplex, tuple[tuple[int, int, int], ...]] = {}
    tetrahedra: set[Simplex] = set()
    cover: list[tuple[Simplex, tuple[tuple[int, int, int], ...]]] = []
    lift_conflicts: list[Simplex] = []

    for origin in itertools.product(range(PERIOD), repeat=3):
        for permutation in itertools.permutations(range(3)):
            points = [tuple(origin)]
            for axis in permutation:
                previous = points[-1]
                points.append(tuple(previous[j] + AXES[axis][j] for j in range(3)))
            indices = [vid(point) for point in points]
            if len(set(indices)) != 4:
                raise AssertionError("Freudenthal tetrahedron degenerates modulo the period")
            key_tet = tuple(sorted(indices))
            tetrahedra.add(key_tet)
            ordered = tuple(point for _, point in sorted(zip(indices, points)))
            cover.append((key_tet, ordered))
            for size in range(1, 5):
                for positions in itertools.combinations(range(4), size):
                    pairs = sorted((indices[j], points[j]) for j in positions)
                    key = tuple(index for index, _ in pairs)
                    lift = tuple(point for _, point in pairs)
                    stored = lift_of.setdefault(key, lift)
                    if stored is not lift and barycentre(stored) != barycentre(lift):
                        lift_conflicts.append(key)

    if len(tetrahedra) != PERIOD**3 * 6:
        raise AssertionError(f"expected 384 tetrahedra, found {len(tetrahedra)}")
    if lift_conflicts:
        raise AssertionError(f"{len(lift_conflicts)} simplices have inconsistent lifts")

    by_dimension: dict[int, list[Simplex]] = {d: [] for d in range(4)}
    for key in lift_of:
        by_dimension[len(key) - 1].append(key)
    for value in by_dimension.values():
        value.sort()

    return {
        "lift_of": lift_of,
        "cover": cover,
        "simplices_by_dimension": by_dimension,
        "tetrahedra": sorted(tetrahedra),
    }


def barycentre(points: Sequence[Sequence[int]]) -> tuple[Fraction, Fraction, Fraction]:
    count = len(points)
    return tuple(  # type: ignore[return-value]
        (Fraction(sum(point[j] for point in points), count)) % PERIOD for j in range(3)
    )


def build_model() -> dict[str, Any]:
    base = build_base_triangulation()
    lift_of = base["lift_of"]
    by_dimension = base["simplices_by_dimension"]

    ordered_simplices: list[Simplex] = []
    for dimension in range(4):
        ordered_simplices.extend(by_dimension[dimension])
    tp_vertex_index = {simplex: position for position, simplex in enumerate(ordered_simplices)}
    for index in range(PERIOD**3):
        if tp_vertex_index[(index,)] != index:
            raise AssertionError("T-vertices must index the first block of T'-vertices")

    tprime_tets: list[Simplex] = []
    for tet in by_dimension[3]:
        for v in tet:
            for w in tet:
                if w == v:
                    continue
                edge = tuple(sorted((v, w)))
                for u in tet:
                    if u == v or u == w:
                        continue
                    triangle = tuple(sorted((v, w, u)))
                    chain = (
                        tp_vertex_index[(v,)],
                        tp_vertex_index[edge],
                        tp_vertex_index[triangle],
                        tp_vertex_index[tet],
                    )
                    if not (chain[0] < chain[1] < chain[2] < chain[3]):
                        raise AssertionError("chain indices are not increasing")
                    tprime_tets.append(chain)
    tprime_tets.sort()
    if len(tprime_tets) != len(by_dimension[3]) * 24:
        raise AssertionError("unexpected number of T'-tetrahedra")
    if len(set(tprime_tets)) != len(tprime_tets):
        raise AssertionError("T' has repeated tetrahedra")

    tprime_simplices = sorted(closure(tprime_tets), key=lambda s: (len(s), s))
    tprime_index = {simplex: position for position, simplex in enumerate(tprime_simplices)}

    barycentres = [barycentre(lift_of[simplex]) for simplex in ordered_simplices]

    model: dict[str, Any] = {
        "period": PERIOD,
        "lift_of": lift_of,
        "T_simplices_by_dimension": by_dimension,
        "T_tetrahedra": by_dimension[3],
        "Tprime_vertex_simplex": ordered_simplices,
        "Tprime_vertex_index": tp_vertex_index,
        "Tprime_vertex_barycentre": barycentres,
        "Tprime_tetrahedra": tprime_tets,
        "Tprime_simplices": tprime_simplices,
        "Tprime_simplex_index": tprime_index,
    }
    model["checks"] = check_triangulations(model)
    model["spines"] = {
        name: build_spine(model, base_point)
        for name, base_point in {**JOHNSON_BASES, **AR_BASES}.items()
    }
    model["handlebodies"] = build_handlebodies(model)
    model["pair_checks"] = {
        "johnson": check_pair(model, model["handlebodies"]["H_J0"], model["handlebodies"]["H_J1"]),
        "ar": check_pair(model, model["handlebodies"]["H_AR0"], model["handlebodies"]["H_AR1"]),
    }
    model["translation"] = check_translation(model, TRANSLATION)
    return model


def check_triangulations(model: dict[str, Any]) -> dict[str, Any]:
    by_dimension = model["T_simplices_by_dimension"]
    tets = by_dimension[3]

    triangle_multiplicity = Counter()
    for tet in tets:
        for triangle in itertools.combinations(tet, 3):
            triangle_multiplicity[triangle] += 1
    t_face_ok = set(triangle_multiplicity.values()) == {2}
    t_chi = (
        len(by_dimension[0]) - len(by_dimension[1]) + len(by_dimension[2]) - len(by_dimension[3])
    )

    star: dict[int, list[Simplex]] = defaultdict(list)
    for tet in tets:
        for vertex in tet:
            star[vertex].append(tet)
    t_links_ok = all(link_is_sphere(cells, vertex) for vertex, cells in star.items())

    tprime_tets = model["Tprime_tetrahedra"]
    tprime_triangle_multiplicity = Counter()
    for tet in tprime_tets:
        for triangle in itertools.combinations(tet, 3):
            tprime_triangle_multiplicity[triangle] += 1
    tp_face_ok = set(tprime_triangle_multiplicity.values()) == {2}
    tp_counts = dimension_counts(model["Tprime_simplices"])
    tp_chi = euler_characteristic(model["Tprime_simplices"])

    tp_star: dict[int, list[Simplex]] = defaultdict(list)
    for tet in tprime_tets:
        for vertex in tet:
            tp_star[vertex].append(tet)
    tp_links_ok = all(link_is_sphere(cells, vertex) for vertex, cells in tp_star.items())

    return {
        "T_vertices": len(by_dimension[0]),
        "T_edges": len(by_dimension[1]),
        "T_triangles": len(by_dimension[2]),
        "T_tetrahedra": len(by_dimension[3]),
        "T_euler_characteristic": t_chi,
        "T_every_triangle_in_two_tetrahedra": t_face_ok,
        "T_all_vertex_links_are_spheres": t_links_ok,
        "Tprime_vertices": tp_counts["dim0"],
        "Tprime_edges": tp_counts["dim1"],
        "Tprime_triangles": tp_counts["dim2"],
        "Tprime_tetrahedra": tp_counts["dim3"],
        "Tprime_euler_characteristic": tp_chi,
        "Tprime_every_triangle_in_two_tetrahedra": tp_face_ok,
        "Tprime_all_vertex_links_are_spheres": tp_links_ok,
    }


