def dual_block_neighbourhood(model: dict[str, Any], spine_vertices: set[int]) -> list[int]:
    """Indices (into Tprime_tetrahedra) of the T'-tetrahedra of N(K;T')."""
    return [
        position
        for position, chain in enumerate(model["Tprime_tetrahedra"])
        if chain[0] in spine_vertices
    ]


def handlebody_report(model: dict[str, Any], tet_positions: Sequence[int], spine_name: str) -> dict[str, Any]:
    tets = [model["Tprime_tetrahedra"][position] for position in tet_positions]
    simplices = closure(tets)
    counts = dimension_counts(simplices)
    chi = euler_characteristic(simplices)

    triangle_multiplicity: Counter[Simplex] = Counter()
    for tet in tets:
        for triangle in itertools.combinations(tet, 3):
            triangle_multiplicity[triangle] += 1
    multiplicity_profile = Counter(triangle_multiplicity.values())
    boundary = sorted(tri for tri, count in triangle_multiplicity.items() if count == 1)
    closed_connected, boundary_chi, boundary_components = surface_is_closed_connected(boundary)
    genus = (2 - boundary_chi) // 2 if boundary_chi % 2 == 0 else None

    spine = model["spines"][spine_name]
    contains_spine = spine["kprime_simplices"] <= simplices

    return {
        "spine": spine_name,
        "tetrahedron_indices": list(tet_positions),
        "tetrahedron_count": len(tets),
        "simplex_counts": counts,
        "euler_characteristic": chi,
        "triangle_multiplicity_profile": {str(k): v for k, v in sorted(multiplicity_profile.items())},
        "manifold_face_multiplicities": set(multiplicity_profile) <= {1, 2},
        "boundary_triangles": boundary,
        "boundary_triangle_count": len(boundary),
        "boundary_is_closed_connected_surface": closed_connected,
        "boundary_euler_characteristic": boundary_chi,
        "boundary_components": boundary_components,
        "boundary_genus": genus,
        "contains_subdivided_spine": contains_spine,
    }


def build_handlebodies(model: dict[str, Any]) -> dict[str, Any]:
    total = len(model["Tprime_tetrahedra"])
    out: dict[str, Any] = {}
    for zero_name, one_name in (("K_J0", "K_J1"), ("K_AR0", "K_AR1")):
        zero_vertices = set(model["spines"][zero_name]["vertices"])
        inside = dual_block_neighbourhood(model, zero_vertices)
        inside_set = set(inside)
        outside = [position for position in range(total) if position not in inside_set]
        out["H_" + zero_name[2:]] = handlebody_report(model, inside, zero_name)
        out["H_" + one_name[2:]] = handlebody_report(model, outside, one_name)
    return out


def check_pair(
    model: dict[str, Any],
    handle_zero: dict[str, Any],
    handle_one: dict[str, Any],
) -> dict[str, Any]:
    total = len(model["Tprime_tetrahedra"])
    zero = set(handle_zero["tetrahedron_indices"])
    one = set(handle_one["tetrahedron_indices"])
    disjoint = not (zero & one)
    fills = len(zero) + len(one) == total and zero | one == set(range(total))
    same_boundary = set(handle_zero["boundary_triangles"]) == set(handle_one["boundary_triangles"])
    genus_ok = handle_zero["boundary_genus"] == 3 and handle_one["boundary_genus"] == 3
    return {
        "tetrahedra_disjoint": disjoint,
        "union_is_Tprime": bool(disjoint and fills),
        "shared_boundary_triangles": same_boundary,
        "common_boundary_triangle_count": len(handle_zero["boundary_triangles"]),
        "common_boundary_genus": handle_zero["boundary_genus"],
        "both_boundaries_genus_three": genus_ok,
        "both_boundaries_closed_connected": bool(
            handle_zero["boundary_is_closed_connected_surface"]
            and handle_one["boundary_is_closed_connected_surface"]
        ),
    }


