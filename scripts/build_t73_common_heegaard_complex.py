def canonical_sha(value: Any) -> str:
    raw = json.dumps(value, sort_keys=True, separators=(",", ":")).encode()
    return hashlib.sha256(raw).hexdigest().upper()


def normalise(document: Any) -> Any:
    """Round-trip through JSON so tuples become lists before hashing/comparing."""
    return json.loads(json.dumps(document, sort_keys=True, separators=(",", ":")))


def vid(point: Sequence[int]) -> int:
    """Index of an integer point of Z^3 reduced modulo the period."""
    x, y, z = (int(c) % PERIOD for c in point)
    return (x * PERIOD + y) * PERIOD + z


def vcoords(index: int) -> tuple[int, int, int]:
    return (index // (PERIOD * PERIOD), (index // PERIOD) % PERIOD, index % PERIOD)


def faces_of(simplex: Simplex, size: int) -> Iterable[Simplex]:
    return itertools.combinations(simplex, size)


def closure(maximal: Iterable[Simplex]) -> set[Simplex]:
    """Every non-empty face of every listed simplex."""
    out: set[Simplex] = set()
    for cell in maximal:
        for size in range(1, len(cell) + 1):
            out.update(itertools.combinations(cell, size))
    return out


def facet_counts(simplices: Iterable[Simplex]) -> dict[Simplex, int]:
    """For each simplex, how many codimension-one cofaces are present."""
    present = set(simplices)
    counts: dict[Simplex, int] = defaultdict(int)
    for cell in present:
        if len(cell) == 1:
            continue
        for facet in itertools.combinations(cell, len(cell) - 1):
            counts[facet] += 1
    return counts


def euler_characteristic(simplices: Iterable[Simplex]) -> int:
    chi = 0
    for cell in simplices:
        chi += (-1) ** (len(cell) - 1)
    return chi


def dimension_counts(simplices: Iterable[Simplex]) -> dict[str, int]:
    counter = Counter(len(cell) - 1 for cell in simplices)
    return {f"dim{d}": counter.get(d, 0) for d in range(4)}


def link_is_sphere(star_top: list[Simplex], apex: int) -> bool:
    """Link of ``apex`` inside the pure 3-complex spanned by ``star_top``.

    Returns True when the link is a connected closed surface with chi = 2.
    """
    triangles = [tuple(v for v in cell if v != apex) for cell in star_top]
    edges: Counter[Simplex] = Counter()
    vertices: set[int] = set()
    for tri in triangles:
        vertices.update(tri)
        for edge in itertools.combinations(tri, 2):
            edges[edge] += 1
    if set(edges.values()) != {2}:
        return False
    if len(vertices) - len(edges) + len(triangles) != 2:
        return False
    adjacency: dict[int, set[int]] = defaultdict(set)
    for a, b in edges:
        adjacency[a].add(b)
        adjacency[b].add(a)
    start = next(iter(vertices))
    seen = {start}
    stack = [start]
    while stack:
        current = stack.pop()
        for other in adjacency[current]:
            if other not in seen:
                seen.add(other)
                stack.append(other)
    return seen == vertices


def surface_is_closed_connected(triangles: Sequence[Simplex]) -> tuple[bool, int, int]:
    """(closed and connected, chi, number of components) of a triangle list."""
    edges: Counter[Simplex] = Counter()
    vertices: set[int] = set()
    for tri in triangles:
        vertices.update(tri)
        for edge in itertools.combinations(tri, 2):
            edges[edge] += 1
    closed = set(edges.values()) == {2}
    chi = len(vertices) - len(edges) + len(triangles)
    adjacency: dict[int, set[int]] = defaultdict(set)
    for a, b in edges:
        adjacency[a].add(b)
        adjacency[b].add(a)
    unseen = set(vertices)
    components = 0
    while unseen:
        start = unseen.pop()
        components += 1
        stack = [start]
        while stack:
            current = stack.pop()
            for other in adjacency[current]:
                if other in unseen:
                    unseen.discard(other)
                    stack.append(other)
    return closed and components == 1, chi, components


