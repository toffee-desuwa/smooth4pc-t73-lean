#!/usr/bin/env python3
"""Common period-4 Freudenthal torus, its barycentric subdivision, and the
four dual-block Heegaard handlebodies used by Lemma P0a.

Model
-----
``T`` is the Freudenthal/Kuhn triangulation of ``T^3 = R^3/(4 Z)^3``: for every
integer origin ``o`` in ``(Z/4)^3`` and every permutation ``(a,b,c)`` of the
three coordinate axes the four points

    o,  o+e_a,  o+e_a+e_b,  o+e_a+e_b+e_c = o+(1,1,1)

span a tetrahedron.  This is exactly the cover used by
``scripts/build_t73_ar_torus.py`` (64 cubes times 6 tetrahedra = 384
tetrahedra); that script reduces vertices by ``v -> (v+2) mod 4`` while this
module reduces by ``v -> v mod 4``.  The two conventions differ by the
translation ``v -> v+(2,2,2)``, a simplicial automorphism of the same mesh, so
the tetrahedron set is identical (``--check`` re-derives it and compares).

``T'`` is the first barycentric subdivision of ``T``: its vertices are the
barycentres of the simplices of ``T`` (64 + 448 + 768 + 384 = 1664 of them) and
its tetrahedra are the maximal chains ``v < e < f < t`` (384 * 24 = 9216).

Spines
------
For a base point ``b`` the *coordinate spine* ``K(b)`` is the union of the three
axis-parallel circles through ``b``; in the period-4 model it is a subcomplex of
``T`` with 10 vertices and 12 edges, so ``rank = E - V + 1 = 3``.

    Johnson pair   K_J^0  = K(0,0,0)      K_J^1  = K(2,2,2)
    AR pair        K_AR^0 = K(3,3,3)      K_AR^1 = K(1,1,1)

``(3,3,3) = (-1,-1,-1) mod 4`` is the AR base point ``Q`` and ``(1,1,1)`` is
``Qbar``.  The integer model of Johnson's affine map ``S(u)=2u-(1/2,1/2,1/2)``
is the translation ``T(v)=v-(1,1,1) mod 4`` of the *same* period-4 mesh.

Dual-block regular neighbourhoods
---------------------------------
For a subcomplex ``K`` of ``T`` the simplicial neighbourhood in ``T'`` is

    N(K;T')  =  union of the closed simplices of T' that meet |K|
             =  union over sigma in K of the dual block D(sigma),

where ``D(sigma)`` is the closure of the set of chains whose *minimal* element
is ``sigma``.  A chain ``c = (sigma_0 < ... < sigma_k)`` meets ``|K|`` iff some
vertex of ``sigma_0`` is a vertex of ``K``; in particular a *tetrahedron*
``(v<e<f<t)`` of ``T'`` lies in ``N(K;T')`` iff its minimal element ``v`` is a
vertex of ``K``.  ``N(K;T')`` is therefore the subcomplex of ``T'`` generated by
those tetrahedra.  This is the definition implemented below; no barycentre
distance comparison is used anywhere.

    H^0 := N(K^0; T')
    H^1 := closure of |T'| - |H^0|, i.e. the subcomplex of T' generated by the
           T'-tetrahedra whose minimal element is NOT a vertex of K^0.

(The frequently quoted identity ``closure of the complement = union of D(sigma)
over sigma not in K`` needs ``K`` full in ``T``.  The coordinate spines are
*not* full in this mesh -- e.g. the T-edge ``{(3,0,0),(0,1,0)}`` has both
endpoints on ``K_J^0`` but is not a spine edge -- so the closure-of-complement
definition above is used, and the fullness computation is reported honestly in
``geometry/t73_*_spines.json``.  Fullness of ``K`` in ``T`` is not needed: the
Rourke--Sanderson regular-neighbourhood theorem is applied to ``K'``, which is
always full in ``T'``, and in any case the certificate that is actually used is
the explicit elementary collapse ``H^i -> K^i`` produced by
``scripts/verify_elementary_collapse.py``.)

Outputs
-------
    geometry/t73_common_torus_triangulation.json
    geometry/t73_johnson_spines.json
    geometry/t73_ar_spines.json
    geometry/t73_handlebody_pair_dual_block.json
"""

from __future__ import annotations

import argparse
import hashlib
import itertools
import json
from collections import Counter, defaultdict
from fractions import Fraction
from pathlib import Path
from typing import Any, Iterable, Sequence


ROOT = Path(__file__).resolve().parents[1]
GEOMETRY = ROOT / "geometry"
TRIANGULATION_OUTPUT = GEOMETRY / "t73_common_torus_triangulation.json"
JOHNSON_SPINE_OUTPUT = GEOMETRY / "t73_johnson_spines.json"
AR_SPINE_OUTPUT = GEOMETRY / "t73_ar_spines.json"
HANDLEBODY_OUTPUT = GEOMETRY / "t73_handlebody_pair_dual_block.json"

PERIOD = 4
AXES = ((1, 0, 0), (0, 1, 0), (0, 0, 1))

JOHNSON_BASES = {"K_J0": (0, 0, 0), "K_J1": (2, 2, 2)}
AR_BASES = {"K_AR0": (3, 3, 3), "K_AR1": (1, 1, 1)}
TRANSLATION = (-1, -1, -1)  # T(v) = v - (1,1,1) mod 4

Simplex = tuple[int, ...]


