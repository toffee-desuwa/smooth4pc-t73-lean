def translate_vertex(index: int, shift: Sequence[int]) -> int:
    coords = vcoords(index)
    return vid(tuple(coords[j] + shift[j] for j in range(3)))


def translate_simplex(simplex: Simplex, shift: Sequence[int]) -> Simplex:
    return tuple(sorted(translate_vertex(v, shift) for v in simplex))


def check_translation(model: dict[str, Any], shift: Sequence[int]) -> dict[str, Any]:
    tets = set(model["T_simplices_by_dimension"][3])
    simplicial = {translate_simplex(tet, shift) for tet in tets} == tets

    tp_index = model["Tprime_vertex_index"]

    def translate_tprime_vertex(index: int) -> int:
        return tp_index[translate_simplex(model["Tprime_vertex_simplex"][index], shift)]

    def translate_tprime_tet(chain: Simplex) -> Simplex:
        return tuple(sorted(translate_tprime_vertex(v) for v in chain))

    spine_images = {}
    for source, target in (("K_J0", "K_AR0"), ("K_J1", "K_AR1")):
        moved = {translate_vertex(v, shift) for v in model["spines"][source]["vertices"]}
        moved_edges = {
            translate_simplex(edge, shift) for edge in map(tuple, model["spines"][source]["edges"])
        }
        spine_images[source] = bool(
            moved == set(model["spines"][target]["vertices"])
            and moved_edges == {tuple(e) for e in model["spines"][target]["edges"]}
        )

    handlebody_images = {}
    if simplicial:
        tprime_tets = model["Tprime_tetrahedra"]
        for source, target in (("H_J0", "H_AR0"), ("H_J1", "H_AR1")):
            moved = {
                translate_tprime_tet(tprime_tets[position])
                for position in model["handlebodies"][source]["tetrahedron_indices"]
            }
            wanted = {
                tprime_tets[position]
                for position in model["handlebodies"][target]["tetrahedron_indices"]
            }
            handlebody_images[source] = moved == wanted
    else:
        handlebody_images = {"H_J0": False, "H_J1": False}

    return {
        "shift": [int(c) for c in shift],
        "formula_original": "S(u)=2u-(1/2,1/2,1/2)",
        "formula_scaled": "T(v)=v-(1,1,1) on the common period-4 Freudenthal mesh",
        "is_simplicial_automorphism_of_T": simplicial,
        "spine_images": spine_images,
        "handlebody_images": handlebody_images,
        "maps_handlebody_pair": bool(
            simplicial and all(spine_images.values()) and all(handlebody_images.values())
        ),
    }


def translation_maps_pair(model: dict[str, Any], shift: Sequence[int]) -> bool:
    """Mutation hook: does ``v -> v + shift`` carry the Johnson pair onto the AR pair?"""
    return bool(check_translation(model, shift)["maps_handlebody_pair"])


