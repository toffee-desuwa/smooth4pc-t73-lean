def committed_ar_tetrahedra() -> set[Simplex]:
    import importlib.util

    path = ROOT / "scripts" / "build_t73_ar_torus.py"
    spec = importlib.util.spec_from_file_location("build_t73_ar_torus", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    torus = module.generate()
    return {tuple(sorted(vid(vertex) for vertex in tet)) for tet in torus["cover_tetrahedra"]}


