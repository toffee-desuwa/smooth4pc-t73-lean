def summary(model: dict[str, Any]) -> dict[str, Any]:
    checks = model["checks"]
    ranks = {name: model["spines"][name]["rank"] for name in model["spines"]}
    return {
        "T_tetrahedra": checks["T_tetrahedra"],
        "Tprime_tetrahedra": checks["Tprime_tetrahedra"],
        "spine_ranks": ranks,
        "handlebody_tetrahedron_counts": {
            name: report["tetrahedron_count"] for name, report in model["handlebodies"].items()
        },
        "handlebody_euler_characteristics": {
            name: report["euler_characteristic"] for name, report in model["handlebodies"].items()
        },
        "boundary_genus": {
            name: report["boundary_genus"] for name, report in model["handlebodies"].items()
        },
        "pair_checks": model["pair_checks"],
        "translation_maps_pair": model["translation"]["maps_handlebody_pair"],
    }


def print_lines(model: dict[str, Any], ar_match: bool | None) -> bool:
    checks = model["checks"]
    ok = True
    ok &= checks["T_euler_characteristic"] == 0
    ok &= checks["T_every_triangle_in_two_tetrahedra"]
    ok &= checks["T_all_vertex_links_are_spheres"]
    ok &= checks["Tprime_euler_characteristic"] == 0
    ok &= checks["Tprime_every_triangle_in_two_tetrahedra"]
    ok &= checks["Tprime_all_vertex_links_are_spheres"]
    ranks = sorted({model["spines"][name]["rank"] for name in model["spines"]})
    ok &= ranks == [3]
    union_ok = all(
        model["pair_checks"][pair]["union_is_Tprime"]
        and model["pair_checks"][pair]["shared_boundary_triangles"]
        for pair in model["pair_checks"]
    )
    genus_ok = all(
        model["pair_checks"][pair]["both_boundaries_genus_three"]
        and model["pair_checks"][pair]["both_boundaries_closed_connected"]
        for pair in model["pair_checks"]
    )
    ok &= union_ok and genus_ok
    ok &= model["translation"]["maps_handlebody_pair"]
    if ar_match is not None:
        ok &= ar_match

    print(f"T_TETRAHEDRA={checks['T_tetrahedra']}")
    print(f"TPRIME_TETRAHEDRA={checks['Tprime_tetrahedra']}")
    print(f"TPRIME_CLOSED_MANIFOLD={'PASS' if checks['Tprime_every_triangle_in_two_tetrahedra'] and checks['Tprime_all_vertex_links_are_spheres'] and checks['Tprime_euler_characteristic'] == 0 else 'FAIL'}")
    print(f"SPINE_RANK={ranks[0] if len(ranks) == 1 else ranks}")
    for name in ("H_J0", "H_J1", "H_AR0", "H_AR1"):
        report = model["handlebodies"][name]
        print(
            f"{name}_TETS={report['tetrahedron_count']} CHI={report['euler_characteristic']} "
            f"BOUNDARY_GENUS={report['boundary_genus']}"
        )
    print(f"COMMON_BOUNDARY_GENUS={model['pair_checks']['johnson']['common_boundary_genus']}")
    print(f"UNION_IS_T3={'PASS' if union_ok else 'FAIL'}")
    print(
        "S_MAPS_HANDLEBODY_PAIR="
        f"{'PASS' if model['translation']['maps_handlebody_pair'] else 'FAIL'}"
    )
    if ar_match is not None:
        print(f"MATCHES_COMMITTED_AR_TORUS={'PASS' if ar_match else 'FAIL'}")
    print(f"DUAL_BLOCK_COMPLEX={'PASS' if ok else 'FAIL'}")
    return bool(ok)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true", help="write the geometry/*.json files")
    parser.add_argument("--check", action="store_true", help="recompute and compare with the committed files")
    parser.add_argument("--skip-ar-crosscheck", action="store_true")
    args = parser.parse_args()

    model = build_model()
    ar_match: bool | None = None
    if not args.skip_ar_crosscheck:
        ar_match = committed_ar_tetrahedra() == set(model["T_simplices_by_dimension"][3])

    produced = documents(model)
    if args.write:
        GEOMETRY.mkdir(parents=True, exist_ok=True)
        for path, document in produced.items():
            path.write_text(dump(document), encoding="utf-8")
            print(f"WROTE={path.relative_to(ROOT)} BYTES={path.stat().st_size}")

    ok = print_lines(model, ar_match)

    if args.check:
        mismatched = []
        for path, document in produced.items():
            if not path.exists():
                mismatched.append(f"{path.relative_to(ROOT)}:MISSING")
                continue
            committed = json.loads(path.read_text(encoding="utf-8"))
            if committed != document:
                mismatched.append(f"{path.relative_to(ROOT)}:DIFFERS")
        print(f"COMMITTED_GEOMETRY={'PASS' if not mismatched else 'FAIL ' + ','.join(mismatched)}")
        ok = ok and not mismatched

    if not args.write and not args.check:
        print(json.dumps(summary(model), indent=2, sort_keys=True))
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
