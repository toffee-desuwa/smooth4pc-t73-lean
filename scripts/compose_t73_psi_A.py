class Generator:
    def __init__(self, document):
        self.index = document["index"]
        self.integer_matrix = document["linear_part_E"]["matrix"]
        self.matrix = [[F(v) for v in row] for row in self.integer_matrix]
        push = document["push_Pi"]
        self.vertices = [point(v) for v in push["vertices"]]
        self.image_vertices = [point(v) for v in push["image_vertices"]]
        self.tetrahedra = [tuple(cell) for cell in push["tetrahedra"]]
        self.maps = [
            ([[F(e) for e in row] for row in record["matrix"]], point(record["translation"]))
            for record in push["cell_maps"]
        ]
        self.halfspaces = [
            (point(item["normal"]), F(item["bound"])) for item in push["support_halfspaces"]
        ]
        self.low = [min(v[i] for v in self.vertices) for i in range(3)]
        self.high = [max(v[i] for v in self.vertices) for i in range(3)]
        self.cell_planes = []
        planes: dict[tuple, None] = {}
        for cell in self.tetrahedra:
            corners = [self.vertices[i] for i in cell]
            inward = []
            for skip in range(4):
                others = corners[:skip] + corners[skip + 1:]
                normal = cross(sub(others[1], others[0]), sub(others[2], others[0]))
                offset = sum(normal[i] * others[0][i] for i in range(3))
                if sum(normal[i] * corners[skip][i] for i in range(3)) < offset:
                    normal = tuple(-c for c in normal)
                    offset = -offset
                inward.append((normal, offset))
                planes[integer_plane(normal, offset)] = None
            self.cell_planes.append(inward)
        self.planes = list(planes)

    def candidates(self, origin):
        ranges = []
        for i in range(3):
            first = ceil_div(F(origin[i]) - self.high[i])
            last = floor_div(F(origin[i]) + 1 - self.low[i])
            ranges.append(range(first, last + 1))
        return [(x, y, z) for x in ranges[0] for y in ranges[1] for z in ranges[2]]

    def inside_support(self, p, shift):
        for normal, bound in self.halfspaces:
            if (
                normal[0] * (p[0] - shift[0])
                + normal[1] * (p[1] - shift[1])
                + normal[2] * (p[2] - shift[2])
            ) > bound:
                return False
        return True

    def locate(self, p, shift):
        local = (p[0] - shift[0], p[1] - shift[1], p[2] - shift[2])
        for index, planes in enumerate(self.cell_planes):
            if all(
                normal[0] * local[0] + normal[1] * local[1] + normal[2] * local[2] >= offset
                for normal, offset in planes
            ):
                return index
        return None

    def apply_cell(self, p, shift, index):
        mat, translation = self.maps[index]
        local = (p[0] - shift[0], p[1] - shift[1], p[2] - shift[2])
        moved = matvec(mat, local)
        return (
            moved[0] + translation[0] + shift[0],
            moved[1] + translation[1] + shift[1],
            moved[2] + translation[2] + shift[2],
        )

    def push_point(self, p):
        origin = tuple(floor_div(c) for c in p)
        for shift in self.candidates(origin):
            if not self.inside_support(p, shift):
                continue
            index = self.locate(p, shift)
            if index is None:
                raise AssertionError("point in the support but in no cell")
            return self.apply_cell(p, shift, index)
        return p

    def push_segment(self, start, end):
        direction = sub(end, start)
        if direction == (0, 0, 0):
            return [self.push_point(end)]
        cuts = {Fraction(0), Fraction(1)}
        for i in range(3):
            d = direction[i]
            if d == 0:
                continue
            lo, hi = (start[i], end[i]) if d > 0 else (end[i], start[i])
            for n in range(floor_div(lo) + 1, ceil_div(hi)):
                t = (Fraction(n) - start[i]) / d
                if 0 < t < 1:
                    cuts.add(t)
        windows: list[list] = []
        ordered_cuts = sorted(cuts)
        for lo, hi in zip(ordered_cuts, ordered_cuts[1:]):
            mid = (lo + hi) / 2
            origin = tuple(floor_div(start[i] + mid * direction[i]) for i in range(3))
            for shift in self.candidates(origin):
                low, high = lo, hi
                empty = False
                for normal, bound in self.halfspaces:
                    value = sum(normal[i] * (start[i] - shift[i]) for i in range(3))
                    slope = sum(normal[i] * direction[i] for i in range(3))
                    if slope == 0:
                        if value > bound:
                            empty = True
                            break
                        continue
                    limit = (bound - value) / slope
                    if slope > 0:
                        high = min(high, limit)
                    else:
                        low = max(low, limit)
                    if low >= high:
                        empty = True
                        break
                if empty or low >= high:
                    continue
                if windows and windows[-1][0] == shift and windows[-1][2] == low:
                    windows[-1][2] = high
                else:
                    windows.append([shift, low, high])
        if not windows:
            return [end]
        images: dict[Fraction, tuple] = {}
        for shift, lo, hi in windows:
            params = {lo, hi}
            for plane in self.planes:
                slope = plane[0] * direction[0] + plane[1] * direction[1] + plane[2] * direction[2]
                if slope == 0:
                    continue
                value = sum(plane[i] * (start[i] - shift[i]) for i in range(3))
                t = (Fraction(plane[3]) - value) / slope
                if lo < t < hi:
                    params.add(t)
            ordered = sorted(params)
            for left, right in zip(ordered, ordered[1:]):
                mid = (left + right) / 2
                probe = tuple(start[i] + mid * direction[i] for i in range(3))
                index = self.locate(probe, shift)
                if index is None:
                    raise AssertionError("sub-segment in the support but in no cell")
                for t in (left, right):
                    raw = tuple(start[i] + t * direction[i] for i in range(3))
                    moved = self.apply_cell(raw, shift, index)
                    if t in images and images[t] != moved:
                        raise AssertionError("push is discontinuous across a cell wall")
                    images[t] = moved
        out = []
        for t in sorted(set(images) | {Fraction(1)}):
            if t == 0:
                continue
            out.append(images.get(t, tuple(start[i] + t * direction[i] for i in range(3))))
        return out

    def push_polyline(self, points):
        out = [self.push_point(points[0])]
        for start, end in zip(points, points[1:]):
            out.extend(self.push_segment(start, end))
        return simplify(out)

    def apply(self, points):
        return self.push_polyline([matvec(self.matrix, p) for p in points])

    def apply_point(self, p):
        return self.push_point(matvec(self.matrix, p))


def simplify(points):
    out = [points[0]]
    for p in points[1:]:
        if p != out[-1]:
            out.append(p)
    if len(out) < 3:
        return out
    kept = [out[0]]
    for index in range(1, len(out) - 1):
        previous, current, following = kept[-1], out[index], out[index + 1]
        line = sub(following, previous)
        offset = sub(current, previous)
        if line != (0, 0, 0) and cross(offset, line) == (0, 0, 0):
            pivot = 0 if line[0] else (1 if line[1] else 2)
            if 0 < offset[pivot] / line[pivot] < 1:
                continue
        kept.append(current)
    kept.append(out[-1])
    return kept


