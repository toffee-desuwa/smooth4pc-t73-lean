def is_spine_vertex(vertex) -> bool:
    return sum(1 for c in vertex if c % PERIOD) <= 1


def hat_support(x):
    base = [floor_div(c) for c in x]
    frac = [x[i] - base[i] for i in range(3)]
    order = sorted(range(3), key=lambda i: (-frac[i], i))
    lam = [
        1 - frac[order[0]],
        frac[order[0]] - frac[order[1]],
        frac[order[1]] - frac[order[2]],
        frac[order[2]],
    ]
    corners = [
        tuple(base),
        tuple(base[i] + (1 if i == order[0] else 0) for i in range(3)),
        tuple(base[i] + (1 if i in (order[0], order[1]) else 0) for i in range(3)),
        tuple(base[i] + 1 for i in range(3)),
    ]
    return [(corners[j], lam[j]) for j in range(4) if lam[j] > 0]


def point_in_H0(x) -> bool:
    pairs = hat_support(x)
    top = max(value for _, value in pairs)
    return any(is_spine_vertex(vertex) for vertex, value in pairs if value == top)


def segment_in_H0(start, end) -> bool:
    direction = sub(end, start)
    if direction == (0, 0, 0):
        return point_in_H0(start)
    cuts = {Fraction(0), Fraction(1)}
    forms = [(start[i], direction[i]) for i in range(3)]
    forms += [
        (start[i] - start[j], direction[i] - direction[j])
        for i in range(3)
        for j in range(i + 1, 3)
    ]
    for value, slope in forms:
        if slope == 0:
            continue
        lo, hi = (value, value + slope) if slope > 0 else (value + slope, value)
        for n in range(floor_div(lo) + 1, ceil_div(hi)):
            t = (Fraction(n) - value) / slope
            if 0 < t < 1:
                cuts.add(t)
    ordered = sorted(cuts)
    for left, right in zip(ordered, ordered[1:]):
        mid = (left + right) / 2
        base_point = tuple(start[i] + mid * direction[i] for i in range(3))
        base = [floor_div(c) for c in base_point]
        frac = [base_point[i] - base[i] for i in range(3)]
        order = sorted(range(3), key=lambda i: (-frac[i], i))
        affine = [(start[i] - base[i], direction[i]) for i in range(3)]
        lam = [
            (1 - affine[order[0]][0], -affine[order[0]][1]),
            (affine[order[0]][0] - affine[order[1]][0], affine[order[0]][1] - affine[order[1]][1]),
            (affine[order[1]][0] - affine[order[2]][0], affine[order[1]][1] - affine[order[2]][1]),
            (affine[order[2]][0], affine[order[2]][1]),
        ]
        pieces = {left, right}
        for i in range(4):
            for j in range(i + 1, 4):
                slope = lam[i][1] - lam[j][1]
                if slope == 0:
                    continue
                t = (lam[j][0] - lam[i][0]) / slope
                if left < t < right:
                    pieces.add(t)
        inner = sorted(pieces)
        for a, b in zip(inner, inner[1:]):
            probe = (a + b) / 2
            if not point_in_H0(tuple(start[i] + probe * direction[i] for i in range(3))):
                return False
    return True


def polyline_in_H0(points) -> bool:
    if not point_in_H0(points[0]):
        return False
    for start, end in zip(points, points[1:]):
        if not segment_in_H0(start, end):
            return False
    return True


def scale_to_period4(points):
    return [tuple(c * PERIOD for c in p) for p in points]


def crosscheck_membership() -> dict[str, Any]:
    triangulation = json.loads(
        (GEOMETRY / "t73_common_torus_triangulation.json").read_text(encoding="utf-8")
    )
    spines = json.loads((GEOMETRY / "t73_johnson_spines.json").read_text(encoding="utf-8"))
    spine_vertices = set(spines["spines"]["K_J0"]["vertices"])
    recorded = {tuple(coords) for coords in spines["spines"]["K_J0"]["vertex_coordinates"]}
    derived = {coords for coords in recorded if sum(1 for c in coords if c % PERIOD) <= 1}
    tetrahedra = triangulation["T"]["tetrahedra"]
    lifts = triangulation["T"]["integer_lifts"]["tetrahedra"]
    weights = [Fraction(4, 10), Fraction(3, 10), Fraction(2, 10), Fraction(1, 10)]
    checked = 0
    mismatches = 0
    for indices, corners in zip(tetrahedra, lifts):
        points = [tuple(F(c) for c in corner) for corner in corners]
        for order in itertools.permutations(range(4)):
            chain = []
            for size in range(1, 5):
                group = [points[order[j]] for j in range(size)]
                chain.append(tuple(sum(g[i] for g in group) / size for i in range(3)))
            probe = tuple(sum(weights[j] * chain[j][i] for j in range(4)) for i in range(3))
            if point_in_H0(probe) != (indices[order[0]] in spine_vertices):
                mismatches += 1
            checked += 1
    return {
        "tprime_tetrahedra_probed": checked,
        "mismatches": mismatches,
        "spine_vertex_rule_matches_commit3": derived == recorded,
        "spine_vertex_count": len(recorded),
    }


