def load_generators() -> list[Generator]:
    paths = sorted(GENERATOR_DIR.glob("gen_[0-9][0-9][0-9].json"))
    if len(paths) != 93:
        raise AssertionError(f"expected 93 generator files, found {len(paths)}")
    generators = [Generator(json.loads(path.read_text(encoding="utf-8"))) for path in paths]
    for position, generator in enumerate(generators):
        if generator.index != position:
            raise AssertionError("generator files are not in index order")
    return generators


def base_curves():
    curves = {}
    for axis in range(3):
        end = [Fraction(0), Fraction(0), Fraction(0)]
        end[axis] = Fraction(1)
        curves[f"C_{axis}"] = [(Fraction(0), Fraction(0), Fraction(0)), tuple(end)]
    for axis in range(3):
        start = [Fraction(0), Fraction(0), Fraction(0)]
        start[(axis + 1) % 3] = FRAMING_EPSILON
        end = list(start)
        end[axis] = Fraction(1)
        curves[f"C_{axis}_plus"] = [tuple(start), tuple(end)]
    return curves


def encode_polyline(points):
    return [[str(c) for c in p] for p in points]


def homology_class(points):
    shift = sub(points[-1], points[0])
    if any(c.denominator != 1 for c in shift):
        raise AssertionError("polyline is not a closed loop in the torus")
    return [int(c) for c in shift]


SPINE_NAMES = [f"C_{axis}" for axis in range(3)]
FRAMING_NAMES = [f"C_{axis}_plus" for axis in range(3)]


def local_normal_form(generators) -> dict[str, Any]:
    """``psi_A = A`` on ``B(0, 1/196104)``: an explicit operator-norm certificate."""
    prefix = [[1, 0, 0], [0, 1, 0], [0, 0, 1]]
    norms = []
    for generator in generators:
        prefix = matmul(generator.integer_matrix, prefix)
        norms.append(infinity_norm(prefix))
    worst = max(norms)
    bound = PROTECTED_RADIUS * worst
    return {
        "claim": "psi_A(x) = A x for every x with sup-norm at most 1/196104",
        "argument": (
            "The support of every push Pi_k is at sup-norm distance 1/8 from Z^3, so a "
            "point of sup-norm below 1/8 is never pushed.  By induction the orbit of x "
            "after k generators is C_k x with C_k = E_{k-1} ... E_0, and "
            "max_k |C_k|_inf * 1/196104 < 1/8, so no push ever fires."
        ),
        "max_prefix_infinity_norm": worst,
        "orbit_bound": str(bound),
        "support_clearance": str(SUPPORT_LATTICE_CLEARANCE),
        "certificate_holds": bound < SUPPORT_LATTICE_CLEARANCE,
    }


def protected_ball_report(generators) -> dict[str, Any]:
    half = PROTECTED_RADIUS / 2
    generator = generators[0]
    column = next(
        j
        for j in range(3)
        if any(generator.integer_matrix[i][j] != (1 if i == j else 0) for i in range(3))
    )
    probe = [Fraction(0), Fraction(0), Fraction(0)]
    probe[column] = half
    linear_image = matvec(generator.matrix, tuple(probe))
    composite_image = matvec([[F(v) for v in row] for row in MATRIX_A], tuple(probe))
    return {
        "radius": str(PROTECTED_RADIUS),
        "push_factors_fix_the_ball_pointwise": True,
        "push_support_sup_norm_distance_to_lattice": str(SUPPORT_LATTICE_CLEARANCE),
        "linear_factors_fix_the_ball_pointwise": False,
        "linear_factor_witness": {
            "generator": generator.index,
            "point": [str(c) for c in probe],
            "sup_norm": str(half),
            "image": [str(c) for c in linear_image],
            "moved": tuple(linear_image) != tuple(probe),
        },
        "psi_A_fixes_the_ball_pointwise": False,
        "psi_A_witness": {
            "point": [str(c) for c in probe],
            "sup_norm": str(half),
            "image": [str(c) for c in composite_image],
            "moved": tuple(composite_image) != tuple(probe),
        },
        "note": (
            "Only the 93 push factors Pi_k fix the protected ball pointwise.  The 93 "
            "linear factors E_k are transvections and do not, so psi_A is the linear "
            "map A on that ball: it fixes 0 and moves everything else there.  A "
            "representative of the Johnson mapping class that is the identity near a "
            "point exists abstractly, but it is not psi_A = Pi_92 E_92 ... Pi_0 E_0."
        ),
    }


def setwise_preservation_report(generators) -> dict[str, Any]:
    generator = generators[0]
    target = None
    for j in range(3):
        column = [generator.integer_matrix[i][j] for i in range(3)]
        if column != [1 if i == j else 0 for i in range(3)]:
            target = j
    probe = [Fraction(0), Fraction(0), Fraction(0)]
    probe[target] = Fraction(1, 4)
    probe = tuple(probe)
    image = generator.apply_point(probe)
    return {
        "claim": "psi_k(H_J^0) = H_J^0 cannot hold for this relative representative",
        "reason": (
            "Set-wise preservation of the dual-block handlebody needs a slide map that "
            "hugs the boundary of the regular neighbourhood of the prefix axis: the "
            "sliding arc has to stay inside the tube around the e_p circle.  The Johnson "
            "relative representative used here bends the diagonal at the quarter points "
            "P = (1/4,1/4) and Q = (3/4,3/4) of the unit square and through m' at "
            "distance 1/4 from both axes.  Scaled to the period-4 mesh those are integer "
            "vertices with two non-zero coordinates; they are not vertices of the spine "
            "K_J^0, their hat-function maximum is attained off the spine, so they lie "
            "outside |H_J^0|.  Pulling the push in towards the axes would repair the "
            "handlebody condition but would drag the support into the protected ball and "
            "destroy the relative property, so one representative does not satisfy both."
        ),
        "witness": {
            "generator": generator.index,
            "point_of_K1": [str(c) for c in probe],
            "point_in_H_J0": point_in_H0(tuple(c * PERIOD for c in probe)),
            "image": [str(c) for c in image],
            "image_in_H_J0": point_in_H0(tuple(c * PERIOD for c in image)),
        },
        "status": "OPEN",
    }


def per_generator_diagnostics(generators) -> list[dict[str, Any]]:
    curves = base_curves()
    out = []
    for generator in generators:
        images = [generator.apply(curves[name]) for name in SPINE_NAMES]
        out.append(
            {
                "index": generator.index,
                "spine_image_vertex_counts": [len(p) for p in images],
                "spine_image_in_H_J0": all(polyline_in_H0(scale_to_period4(p)) for p in images),
                "max_sup_norm_distance_to_K1": str(
                    max(polyline_max_distance(p) for p in images)
                ),
                "bent_path": encode_polyline(images[
                    next(
                        j
                        for j in range(3)
                        if [generator.integer_matrix[i][j] for i in range(3)]
                        != [1 if i == j else 0 for i in range(3)]
                    )
                ]),
            }
        )
    return out


def prefix_transport(generators, budget: int, progress: bool) -> dict[str, Any]:
    curves = base_curves()
    reports = [
        {
            "steps": 0,
            "spine_vertex_counts": [len(curves[name]) for name in SPINE_NAMES],
            "framing_vertex_counts": [len(curves[name]) for name in FRAMING_NAMES],
            "spine_image_in_H_J0": all(
                polyline_in_H0(scale_to_period4(curves[name])) for name in SPINE_NAMES
            ),
            "max_curve_distance_to_K1": str(
                max(polyline_max_distance(curves[name]) for name in SPINE_NAMES)
            ),
        }
    ]
    first_exit = None
    completed = 0
    for step, generator in enumerate(generators, start=1):
        for name in list(curves):
            curves[name] = generator.apply(curves[name])
        completed = step
        polylines = [curves[name] for name in SPINE_NAMES]
        inside = all(polyline_in_H0(scale_to_period4(p)) for p in polylines)
        if not inside and first_exit is None:
            first_exit = step
        reports.append(
            {
                "steps": step,
                "spine_vertex_counts": [len(p) for p in polylines],
                "framing_vertex_counts": [len(curves[name]) for name in FRAMING_NAMES],
                "spine_image_in_H_J0": inside,
                "max_curve_distance_to_K1": str(
                    max(polyline_max_distance(p) for p in polylines)
                ),
            }
        )
        if progress:
            print(f"  prefix {step:3d} {reports[-1]['spine_vertex_counts']}", flush=True)
        if max(len(curve) for curve in curves.values()) > budget:
            break
    payload = {
        name: encode_polyline(curve) for name, curve in sorted(curves.items())
    }
    counts = [max(item["spine_vertex_counts"]) for item in reports]
    ratios = [
        str(Fraction(counts[i + 1], counts[i])) for i in range(len(counts) - 1) if counts[i]
    ]
    return {
        "vertex_budget": budget,
        "prefixes_completed": completed,
        "prefixes_requested": len(generators),
        "complete": completed == len(generators),
        "reports": reports,
        "first_prefix_leaving_H_J0": first_exit,
        "max_spine_vertex_counts": counts,
        "growth_ratios": ratios,
        "polygon_sha256": canonical_sha(payload),
        "final_homology_classes": {
            name: homology_class(curve) for name, curve in sorted(curves.items())
        },
        "status": (
            "COMPLETE"
            if completed == len(generators)
            else "OPEN: the exact polygon transport was stopped by the vertex budget; "
            "the number of linearity domains of the composite grows multiplicatively "
            "(measured factor about 1.25 per generator), so the exact 93-fold image "
            "polygon has of order 10^9 vertices and is not computed here"
        ),
    }


def point_sample_transport(generators, count: int) -> dict[str, Any]:
    """Exact images of a finite point sample under the full 93-fold composite."""
    samples: dict[str, list] = {}
    for axis in range(3):
        for name, offset in (
            (f"C_{axis}", Fraction(0)),
            (f"C_{axis}_plus", FRAMING_EPSILON),
        ):
            points = []
            for j in range(count):
                p = [Fraction(0), Fraction(0), Fraction(0)]
                p[axis] = Fraction(j, count)
                p[(axis + 1) % 3] = offset
                points.append(tuple(p))
            samples[name] = points
    images = {}
    for name, points in samples.items():
        current = points
        for generator in generators:
            current = [generator.apply_point(p) for p in current]
        images[name] = current
    payload = {name: encode_polyline(points) for name, points in sorted(images.items())}
    digits = max(
        len(str(c.denominator)) for points in images.values() for p in points for c in p
    )
    origin = images["C_0"][0]
    return {
        "sample_count_per_curve": count,
        "sample_rule": "the points j/count on each loop, j = 0 .. count-1",
        "image_sha256": canonical_sha(payload),
        "max_denominator_decimal_digits": digits,
        "image_of_the_origin": [str(c) for c in origin],
        "origin_is_fixed": tuple(origin) == (Fraction(0), Fraction(0), Fraction(0)),
        "first_images": {
            name: [[str(c) for c in p] for p in points[:2]]
            for name, points in sorted(images.items())
        },
        "note": (
            "This is an exact point sample of psi_A, not the image polygon: the "
            "polygon between two sampled points is not a straight segment."
        ),
    }


THETA_PATH = GENERATOR_DIR / "gen_093_section_straightening.json"


def section_straightening_report(generators) -> dict[str, Any]:
    """``Psi = psi_A o theta`` is the identity on the cube of radius ``r_inner``.

    ``theta`` is the linear map ``A^{-1}`` on ``C_in`` (its innermost cone cells
    all carry that one matrix), and ``A^{-1} C_in`` lies well inside the cube on
    which ``psi_A`` is exactly ``A``.  So ``Psi(x) = A A^{-1} x = x`` there.  The
    check below is not only that argument: a sample of points of ``C_in``
    (including its corners) is pushed through ``A^{-1}`` and then through all 93
    generators one point at a time, and compared with the starting point.
    """
    if not THETA_PATH.exists():
        return {"status": "MISSING", "file": str(THETA_PATH.relative_to(ROOT))}
    theta = json.loads(THETA_PATH.read_text(encoding="utf-8"))
    inverse_a = [[F(v) for v in row] for row in theta["matrix_A_inverse"]]
    matrix_a = [[F(v) for v in row] for row in MATRIX_A]
    r_inner = F(theta["r_inner"])
    r_outer = F(theta["r_outer"])
    norm = max(sum(abs(entry) for entry in row) for row in inverse_a)
    if norm.denominator != 1:
        raise AssertionError("A^{-1} is not integral")
    norm = int(norm)

    linear = local_normal_form(generators)
    inside_regime = norm * r_inner < r_outer and r_outer <= PROTECTED_RADIUS

    probes = [(Fraction(0), Fraction(0), Fraction(0))]
    for sx in (1, -1):
        for sy in (1, -1):
            for sz in (1, -1):
                probes.append((sx * r_inner, sy * r_inner, sz * r_inner))
    for j in (1, 2, 3, 5, 7):
        probes.append(
            (r_inner * Fraction(j, 8), -r_inner * Fraction(j, 11), r_inner * Fraction(j, 13))
        )
    failures = []
    for probe in probes:
        moved = matvec(inverse_a, probe)
        if max(abs(c) for c in moved) >= r_outer:
            failures.append("theta image leaves the linear regime")
            continue
        current = moved
        for generator in generators:
            current = generator.apply_point(current)
        if tuple(current) != tuple(probe):
            failures.append(f"Psi moved {[str(c) for c in probe]} to {[str(c) for c in current]}")
    return {
        "file": str(THETA_PATH.relative_to(ROOT)),
        "theta_sha256": theta["sha256"],
        "r_outer": str(r_outer),
        "r_inner": str(r_inner),
        "matrix_A_inverse_infinity_norm": norm,
        "theta_image_of_C_in_sup_radius_bound": str(norm * r_inner),
        "inside_linear_regime_of_psi_A": inside_regime,
        "linear_regime_certificate": linear["certificate_holds"],
        "probe_count": len(probes),
        "probes_returned_to_themselves": not failures,
        "failures": failures,
        "induced_H1_matrix_of_Psi": MATRIX_A,
        "induced_H1_note": (
            "theta is supported in a ball, hence isotopic to the identity and trivial on "
            "H_1, so Psi = psi_A o theta induces the same matrix A as psi_A."
        ),
        "matrix_A_times_its_inverse_is_identity": matmul(
            [[int(v) for v in row] for row in MATRIX_A],
            [[int(entry) for entry in row] for row in inverse_a],
        )
        == [[1, 0, 0], [0, 1, 0], [0, 0, 1]],
        "fixed_ball_radius": str(r_inner),
        "status": "PASS" if (not failures and inside_regime) else "FAIL",
    }


def run(budget: int = DEFAULT_VERTEX_BUDGET, samples: int = DEFAULT_SAMPLE_COUNT,
        progress: bool = False, limit: int | None = None) -> dict[str, Any]:
    generators = load_generators()
    if limit is not None:
        generators = generators[:limit]

    composite = [[1, 0, 0], [0, 1, 0], [0, 0, 1]]
    for generator in generators:
        composite = matmul(generator.integer_matrix, composite)

    per_generator = per_generator_diagnostics(generators)
    transport = prefix_transport(generators, budget, progress)
    sample = point_sample_transport(generators, samples)

    document: dict[str, Any] = {
        "schema": "t73_psi_A_composite/v1",
        "generator": "scripts/compose_t73_psi_A.py",
        "generator_source": "geometry/t73_johnson_generators/gen_000.json ... gen_092.json",
        "generator_count": len(generators),
        "composition_order": "psi_A = psi_92 o ... o psi_0 (psi_0 applied to points first)",
        "composite_linear_matrix": composite,
        "matrix_A": MATRIX_A,
        "composite_matrix_equals_A": composite == MATRIX_A,
        "induced_H1_matrix": composite,
        "spine_image_homology_classes": {
            f"C_{axis}": [composite[row][axis] for row in range(3)] for axis in range(3)
        },
        "framing": {
            "epsilon": str(FRAMING_EPSILON),
            "rule": "C_i^+ = C_i + epsilon * e_{(i+1) mod 3} (Aitchison-Rubinstein product framing)",
            "homology_classes": {
                f"C_{axis}_plus": [composite[row][axis] for row in range(3)] for axis in range(3)
            },
        },
        "local_normal_form": local_normal_form(generators),
        "protected_ball": protected_ball_report(generators),
        "section_straightening": section_straightening_report(generators),
        "exact_prefix_transport": transport,
        "point_sample_transport": sample,
        "handlebody_diagnostics": {
            "reference": "geometry/t73_handlebody_pair_dual_block.json (H_J0, period-4 mesh)",
            "period_conversion": "period-1 points are multiplied by 4",
            "test": (
                "membership is tested against the CLOSED subcomplex |H_J^0| (a stronger "
                "requirement to fail than the interior).  A segment is inside iff every "
                "point is: the segment is cut at every wall of the piecewise-linear "
                "structure (the integer planes and the diagonal planes x_i - x_j in Z of "
                "the Freudenthal mesh, then the crossings of the four barycentric "
                "coordinates), and on each resulting open piece the set of vertices "
                "attaining the maximal hat value is constant, so one interior probe per "
                "piece decides it exactly.  The probe is cross-checked against COMMIT 3 on "
                "an interior point of each of the 9216 T'-tetrahedra (--crosscheck)."
            ),
            "per_generator": per_generator,
            "per_generator_pass_count": sum(
                1 for item in per_generator if item["spine_image_in_H_J0"]
            ),
            "first_prefix_leaving_H_J0": transport["first_prefix_leaving_H_J0"],
            "composite_spine_image_in_H_J0": False
            if transport["first_prefix_leaving_H_J0"] is not None
            else None,
            "setwise_preservation": setwise_preservation_report(generators),
        },
        "attaching_link_status": (
            "OPEN: without exact set-wise preservation of the Heegaard pair the "
            "Aitchison-Rubinstein attaching curves psi_A(C_i^+) on the splitting surface "
            "are not defined.  No attaching link is produced by this script."
        ),
    }
    document["psi_A_sha256"] = canonical_sha(document)
    return document


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--budget", type=int, default=DEFAULT_VERTEX_BUDGET)
    parser.add_argument("--samples", type=int, default=DEFAULT_SAMPLE_COUNT)
    parser.add_argument("--limit", type=int)
    parser.add_argument("--progress", action="store_true")
    parser.add_argument("--crosscheck", action="store_true")
    args = parser.parse_args()

    ok = True
    if args.crosscheck:
        report = crosscheck_membership()
        print(json.dumps(report, indent=2, sort_keys=True))
        print(f"H_J0_MEMBERSHIP_CROSSCHECK={'PASS' if report['mismatches'] == 0 else 'FAIL'}")
        ok = ok and report["mismatches"] == 0

    document = run(
        budget=args.budget, samples=args.samples, progress=args.progress, limit=args.limit
    )
    ok = ok and document["composite_matrix_equals_A"]
    ok = ok and document["local_normal_form"]["certificate_holds"]

    if args.write and args.limit is None:
        OUTPUT.write_text(
            json.dumps(document, sort_keys=True, separators=(",", ":")) + "\n", encoding="utf-8"
        )
        print(f"WROTE={OUTPUT.relative_to(ROOT)} BYTES={OUTPUT.stat().st_size}")
    if args.check:
        if not OUTPUT.exists():
            print("COMMITTED_PSI_A=FAIL MISSING")
            ok = False
        else:
            same = json.loads(OUTPUT.read_text(encoding="utf-8")) == document
            print(f"COMMITTED_PSI_A={'PASS' if same else 'FAIL'}")
            ok = ok and same

    diagnostics = document["handlebody_diagnostics"]
    transport = document["exact_prefix_transport"]
    print(f"JOHNSON_GENERATORS={document['generator_count']}")
    print(f"INDUCED_MATRIX_EQUALS_A={'PASS' if document['composite_matrix_equals_A'] else 'FAIL'}")
    print(
        "PROTECTED_BALL_FIXED="
        f"{'PASS' if document['protected_ball']['psi_A_fixes_the_ball_pointwise'] else 'FAIL'}"
    )
    print("PROTECTED_BALL_FIXED_BY_PUSH_FACTORS=PASS")
    print(
        "PSI_A_ON_PROTECTED_BALL=LINEAR_A "
        f"certificate={'PASS' if document['local_normal_form']['certificate_holds'] else 'FAIL'}"
    )
    section = document["section_straightening"]
    print(
        f"PSI_FIXES_SECTION_BALL={section['status']} radius={section.get('fixed_ball_radius')}"
    )
    print(
        "SPINE_IMAGE_IN_H0_PER_GENERATOR="
        f"{diagnostics['per_generator_pass_count']}/{document['generator_count']}"
    )
    print(
        "COMPOSITE_SPINE_IMAGE_IN_H0=FAIL "
        f"first_exit_step={diagnostics['first_prefix_leaving_H_J0']}"
    )
    print("HEEGAARD_PAIR_EXACT_PRESERVATION=OPEN")
    print(
        "EXACT_COMPOSITE_POLYGON="
        f"{'COMPLETE' if transport['complete'] else 'OPEN'} "
        f"prefixes_completed={transport['prefixes_completed']}/{transport['prefixes_requested']} "
        f"max_vertices={max(transport['max_spine_vertex_counts'])}"
    )
    print(f"PREFIX_POLYGON_SHA256={transport['polygon_sha256']}")
    print(f"POINT_SAMPLE_SHA256={document['point_sample_transport']['image_sha256']}")
    print(f"PSI_A_SHA256={document['psi_A_sha256']}")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
