def canonical_sha(value: Any) -> str:
    raw = json.dumps(value, sort_keys=True, separators=(",", ":")).encode()
    return hashlib.sha256(raw).hexdigest().upper()


def F(value) -> Fraction:
    return Fraction(value)


def point(raw):
    return (F(raw[0]), F(raw[1]), F(raw[2]))


def sub(a, b):
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def cross(u, v):
    return (
        u[1] * v[2] - u[2] * v[1],
        u[2] * v[0] - u[0] * v[2],
        u[0] * v[1] - u[1] * v[0],
    )


def matmul(left, right):
    return [[sum(left[i][k] * right[k][j] for k in range(3)) for j in range(3)] for i in range(3)]


def matvec(mat, vector):
    return tuple(
        mat[i][0] * vector[0] + mat[i][1] * vector[1] + mat[i][2] * vector[2] for i in range(3)
    )


def infinity_norm(mat) -> int:
    return max(sum(abs(entry) for entry in row) for row in mat)


def floor_div(value: Fraction) -> int:
    return value.numerator // value.denominator


def ceil_div(value: Fraction) -> int:
    return -((-value.numerator) // value.denominator)


def gcd(a: int, b: int) -> int:
    while b:
        a, b = b, a % b
    return abs(a)


def integer_plane(normal, offset):
    values = list(normal) + [offset]
    denominator = 1
    for value in values:
        denominator = denominator * value.denominator // gcd(denominator, value.denominator)
    integers = [int(value * denominator) for value in values]
    common = 0
    for value in integers:
        common = gcd(common, abs(value))
    if common:
        integers = [value // common for value in integers]
    for value in integers:
        if value:
            if value < 0:
                integers = [-v for v in integers]
            break
    return tuple(integers)


