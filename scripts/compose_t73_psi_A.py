#!/usr/bin/env python3
"""COMMIT 4a -- compose the 93 PL Johnson generators into ``psi_A`` and report
the honest diagnostics against the COMMIT 3 handlebody ``H_J^0``.

Composition order
-----------------
``psi_A = psi_92 o ... o psi_0`` (``psi_0`` is applied to points first), because
``E_92 * ... * E_0 = A``; see the module docstring of
``scripts/build_t73_johnson_pl_generators.py``.  The composite induced matrix is
recomputed here from the generator files and compared with ``A``.

What is exact and complete
--------------------------
* the composite linear part ``E_92 * ... * E_0 = A`` and hence the induced map
  on ``H_1(T^3)`` and the homology classes of all six image curves;
* the local normal form ``psi_A(x) = A x`` for ``|x|_sup <= 1/196104``, with the
  operator-norm certificate that no push ever fires on those orbits;
* the per-generator diagnostics: for each of the 93 generators, the exact image
  of ``K1`` (a five-vertex bent path plus two untouched axis circles), whether it
  lies in ``|H_J^0|``, and its exact sup-norm distance from ``K1``;
* the exact prefix transport of the three spine loops and of the three framing
  push-offs ``C_i^+ = C_i + (1/1000) e_{i+1}``, carried as far as the vertex
  budget allows, with the exact vertex counts at every step;
* the exact image under the *full* 93-fold composite of a finite sample of
  points of each curve (point transport does not suffer the polyline blow-up).

What is NOT computed, and why
-----------------------------
The complete exact polygon ``psi_A(C_i)`` is not produced.  ``psi_k`` is affine
on 24 cells plus their complement, so the ``k``-fold composite is affine only on
the common refinement, and the number of linearity domains a curve meets grows
multiplicatively.  Measured on this factorisation the vertex count of the exact
image of ``C_2`` is

    5, 11, 19, 31, ..., 3329 (step 27), ..., 10440 (step 32)

i.e. a growth factor near ``1.25`` per generator; extrapolating to 93 generators
gives of order ``10^9`` vertices, with rational coordinates whose denominators
also grow.  This is a property of the object, not of the implementation: the
exact polygon is reported as OPEN together with the measured growth, and no
approximation is substituted for it.

The membership test for ``|H_J^0|``
----------------------------------
``H_J^0 = N(K_J^0; T')`` is generated by the ``T'``-tetrahedra whose minimal
chain element is a vertex of the spine ``K_J^0`` (period-4 model, see
``scripts/build_t73_common_heegaard_complex.py``).  A point lies in a closed
``T'``-tetrahedron ``(v<e<f<t)`` iff its barycentric coordinates inside ``t``
decrease along the chain, so

    x in |H_J^0|  <=>  the maximum of the piecewise-linear hat functions
                       ``lambda_w(x)``, ``w`` a vertex of ``T``, is attained at
                       some vertex of ``K_J^0``.

``--crosscheck`` re-derives this against the committed COMMIT 3 data by running
it on an interior point of each of the 9216 ``T'``-tetrahedra.  Period
conversion: period-1 points are multiplied by 4.

Protected ball -- stated honestly
---------------------------------
Every push ``Pi_k`` fixes ``B(0, 1/196104)`` pointwise (its support is at
sup-norm distance ``1/8`` from the lattice).  Every *linear* factor ``E_k`` does
not: it is a transvection and moves every point with ``x_t != 0``.  Consequently
``psi_A`` restricted to the protected ball is exactly the linear map ``A``: it
fixes ``0`` but no ball around it.  Both facts are recorded with explicit
witnesses.  No attaching link is produced: without exact set-wise preservation
of the handlebody pair the Aitchison--Rubinstein curves ``psi_A(C_i^+)`` on the
Heegaard surface are not defined, and that stays OPEN.

Section straightening
---------------------
``geometry/t73_johnson_generators/gen_093_section_straightening.json`` records a
further explicit PL homeomorphism ``theta`` of ``T^3``, supported in the
protected cube and equal to ``A^{-1}`` on a small cube ``C_in``, built by
``scripts/build_t73_section_straightening.py``.  ``section_straightening`` below
records that ``Psi = psi_A o theta`` is the identity on ``C_in`` pointwise: the
argument is that ``A^{-1} C_in`` stays inside the cube where ``psi_A`` is
literally ``A``, and the check is that a sample of points of ``C_in``, its
corners included, is pushed through ``A^{-1}`` and then through all 93
generators one point at a time and comes back to itself.
"""

