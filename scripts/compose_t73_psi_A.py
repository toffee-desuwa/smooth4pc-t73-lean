def circle_distance(value: Fraction) -> Fraction:
    frac = value - floor_div(value)
    return frac if frac + frac <= 1 else 1 - frac


def distance_to_K1(p) -> Fraction:
    """Sup-norm distance in ``T^3`` to the three coordinate axis circles.

    The distance to the ``e_i`` circle is ``max_{j != i} d(x_j, Z)``, so the
    distance to their union is the *median* of the three circle distances.
    """
    values = sorted(circle_distance(c) for c in p)
    return values[1]


def segment_max_distance(start, end, cap: Fraction) -> Fraction:
    direction = sub(end, start)
    if direction == (0, 0, 0):
        return distance_to_K1(start)
    params = {Fraction(0), Fraction(1)}
    for i in range(3):
        d = direction[i]
        if d == 0:
            continue
        lo, hi = (start[i], end[i]) if d > 0 else (end[i], start[i])
        for n in range(ceil_div(lo * 2), floor_div(hi * 2) + 1):
            t = (Fraction(n, 2) - start[i]) / d
            if 0 < t < 1:
                params.add(t)
    best = Fraction(0)
    ordered = sorted(params)
    for left, right in zip(ordered, ordered[1:]):
        mid = (left + right) / 2
        base = tuple(start[i] + mid * direction[i] for i in range(3))
        lines = []
        for i in range(3):
            offset = floor_div(base[i])
            if base[i] + base[i] <= 2 * offset + 1:
                lines.append((direction[i], start[i] - offset))
            else:
                lines.append((-direction[i], Fraction(offset + 1) - start[i]))
        pieces = {left, right}
        for i in range(3):
            for j in range(i + 1, 3):
                slope = lines[i][0] - lines[j][0]
                if slope == 0:
                    continue
                t = (lines[j][1] - lines[i][1]) / slope
                if left < t < right:
                    pieces.add(t)
        for t in sorted(pieces):
            value = distance_to_K1(tuple(start[i] + t * direction[i] for i in range(3)))
            if value > best:
                best = value
                if best >= cap:
                    return best
    return best


def polyline_max_distance(points, cap=Fraction(1, 2)) -> Fraction:
    best = Fraction(0)
    for start, end in zip(points, points[1:]):
        best = max(best, segment_max_distance(start, end, cap))
        if best >= cap:
            return best
    return best


def polyline_vertex_max_distance(points) -> Fraction:
    return max(distance_to_K1(p) for p in points)


